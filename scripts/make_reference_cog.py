#!/usr/bin/env python3
"""Independent reference curve-of-growth values for tests/physics.html.

    python scripts/make_reference_cog.py        (needs numpy + scipy)

W is computed with the exact Voigt function (scipy.special.wofz) and adaptive
quadrature (scipy.integrate.quad) over geometrically growing intervals, plus
the analytic Lorentzian tail -- no code shared with assets/js/physics.js.
Line data are read from data/lines.js (run build_data.py first).
"""
import json
import re
from pathlib import Path

import numpy as np
from scipy.integrate import quad
from scipy.special import wofz

ROOT = Path(__file__).resolve().parent.parent
e, me, c = 4.80320471e-10, 9.1093837015e-28, 2.99792458e10
PI_E2_MEC = np.pi * e * e / (me * c)

IDS = ["HI_1215", "HI_1025", "OVI_1031", "SiII_1260", "MgII_2796", "FeII_2382",
       "NeVIII_770", "CIV_1548", "OVII_21p60"]
B = [5.0, 30.0, 100.0]
LOGN = [10.0, 12.0, 13.0, 14.0, 15.0, 16.0, 17.0, 18.0, 19.0, 20.0, 21.0, 22.0]


def lines():
    t = (ROOT / "data" / "lines.js").read_text(encoding="utf-8")
    i = t.index("window.CGM_LINES = ") + len("window.CGM_LINES = ")
    j = t.index("];", i) + 1
    return {l["id"]: l for l in json.loads(re.sub(r",\s*\]$", "]", t[i:j]))}


def W(line, N, b):
    lam = line["wave"] * 1e-8
    bc = b * 1e5
    t0 = np.sqrt(np.pi) * e * e / (me * c) * line["f"] * lam * N / bc
    a = line["Gamma"] * lam / (4 * np.pi * bc)
    H = lambda u: wofz(u + 1j * a).real
    g = lambda u: -np.expm1(-t0 * H(u))
    # integrate on [0,1], [1,2], [2,4], ... until tau < 1e-12, then add the tail
    I, lo, hi = 0.0, 0.0, 1.0
    while True:
        val, _ = quad(g, lo, hi, epsabs=0, epsrel=1e-11, limit=400)
        I += val
        if t0 * H(hi) < 1e-12 or hi > 1e12:
            break
        lo, hi = hi, hi * 2
    I += t0 * a / (np.sqrt(np.pi) * hi)
    return 2 * (line["wave"] * b / (c / 1e5)) * I


def main():
    L = lines()
    out = []
    for lid in IDS:
        l = L[lid]
        for b in B:
            for x in LOGN:
                out.append(dict(id=lid, b=b, logN=x, W=W(l, 10 ** x, b)))
    path = ROOT / "tests" / "reference_cog.js"
    path.write_text("// GENERATED by scripts/make_reference_cog.py (scipy wofz + quad)\n"
                    "window.REFERENCE_COG = " + json.dumps(out) + ";\n", encoding="utf-8")
    print(f"wrote {len(out)} reference points to {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
