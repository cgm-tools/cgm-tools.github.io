#!/usr/bin/env python3
"""Compare the hard-coded numbers of the original site (commit 2dbc418) with
the rebuilt, source-traceable data and write DATA_CHANGES.md.

    python3 scripts/compare_legacy.py      (run after build_data.py)
"""
import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LEGACY = "2dbc418"

# Lines removed on purpose, with the reason.
REMOVED = {
    ("He I", 10830.0): "not a resonance line: lower level is the metastable 2³S, not the ground state",
    ("He II", 1640.4): "He II 1640 is n=2→3 (Balmer-α); its lower level is not the ground state, so it is not seen in absorption",
    ("O V", 1371.296): "lower level 2s2p ¹P is excited (not a ground-state absorption line)",
    ("S IV", 1072.996): "lower level is the excited ²P₃/₂ fine-structure level (E_low = 951 cm⁻¹, Morton 2003); not a ground-state line",
    ("Si I", 1526.707): "1526.707 Å is a Si II line, not Si I; replaced by real Si I lines (2515, 1845 Å)",
    ("Ne II", 780.324): "780.324 Å is the Ne VIII red doublet member, not Ne II; replaced by Ne II 460.7/446.3 Å",
    ("Fe X", 174.531): "coronal EUV emission line, not part of the CGM absorption list",
    ("S XIII", 35.212): "S XIII is Be-like (not He-like); line not in Verner+1996 as listed; removed",
    ("S XIV", 30.438): "S XIV is Li-like (not H-like); not a commonly used CGM line; removed",
    ("O I", 988.578): "weak J-component (f = 5.5e-4); replaced by the strong O I 988.773 line (f = 0.0465)",
}


def legacy(fname):
    return subprocess.run(["git", "-C", str(ROOT), "show", f"{LEGACY}:{fname}"],
                          capture_output=True, text=True, check=True).stdout


def load_js(path, var):
    t = (ROOT / path).read_text(encoding="utf-8")
    i = t.index(f"window.{var} = ") + len(f"window.{var} = ")
    j = t.index("];", i) + 1
    return json.loads(re.sub(r",\s*\]$", "]", t[i:j]))


def main():
    lines = load_js("data/lines.js", "CGM_LINES")
    ions = {i["ion"]: i for i in load_js("data/ions.js", "CGM_IONS")}

    # --- legacy curve-of-growth transitions (lambda, f, gamma) -----------------
    cog = legacy("cog.html")
    old_tr = [dict(ion=m[0], wave=float(m[1]), f=float(m[2]), gamma=float(m[3]))
              for m in re.findall(r"ion:'([^']+)',\s*lambda:\s*([\d.]+),\s*f:([\d.]+),\s*gamma:([\deE.+-]+)", cog)]
    # --- legacy ion table: IE and transitions -----------------------------------
    ionsh = legacy("ions.html")
    old_ions = []
    for m in re.finditer(r"name:'([^']+)',\s*charge:\s*(\d+),\s*ie_eV:([\d.]+|null),\s*form_eV:([\d.]+|null),\s*transitions:\[(.*?)\]", ionsh, re.S):
        trs = [dict(wave=float(a), f=float(b)) for a, b in re.findall(r"lambda:\s*([\d.]+),f:([\d.]+)", m.group(5))]
        old_ions.append(dict(ion=m.group(1).strip(), ie=None if m.group(3) == "null" else float(m.group(3)),
                             form=None if m.group(4) == "null" else float(m.group(4)), trs=trs))
    old_tab = {}
    for oi in old_ions:
        for t in oi["trs"]:
            old_tab[(oi["ion"], t["wave"])] = dict(ion=oi["ion"], wave=t["wave"], f_table=t["f"])
    for t in old_tr:
        old_tab.setdefault((t["ion"], t["wave"]), dict(ion=t["ion"], wave=t["wave"]))
        old_tab[(t["ion"], t["wave"])].update(f_cog=t["f"], gamma=t["gamma"])

    def new_for(ion, wave):
        c = [l for l in lines if l["ion"] == ion and abs(l["wave"] - wave) < 0.1 and not l.get("excited")]
        return min(c, key=lambda l: abs(l["wave"] - wave)) if c else None

    def pct(a, b):
        return f"{(a - b) / b:+.0%}" if b else ""

    out = ["# Data changes relative to the original site",
           "",
           f"Generated by `scripts/compare_legacy.py`: every number hard-coded in the original "
           f"`cog.html` / `ions.html` (commit `{LEGACY}`) compared with the rebuilt data, which is read "
           "directly from the source files in `sources/` (see `sources/README.md`).",
           "",
           "Δ is (old − new)/new.  Rows marked **bold** changed by more than 10%.",
           "",
           "## Transitions kept (corrected values)",
           "",
           "| Line | λ old (Å) | λ new (Å) | f old (table) | f old (COG) | f new | Δf | Γ old (s⁻¹) | Γ new (s⁻¹) | ΔΓ | Source |",
           "|---|---|---|---|---|---|---|---|---|---|---|"]
    removed, n_big = [], 0
    for key in sorted(old_tab, key=lambda k: (k[0], -k[1])):
        o = old_tab[key]
        n = new_for(o["ion"], o["wave"])
        if n is None:
            removed.append(o)
            continue
        fo = o.get("f_cog", o.get("f_table"))
        df = (fo - n["f"]) / n["f"]
        dg = (o["gamma"] - n["Gamma"]) / n["Gamma"] if "gamma" in o else 0
        big = abs(df) > 0.10 or abs(dg) > 0.10 or abs(o["wave"] - n["wave"]) > 0.01 or \
            ("f_table" in o and "f_cog" in o and abs(o["f_table"] - o["f_cog"]) / n["f"] > 0.10)
        n_big += big
        b = "**" if big else ""
        bf = "**" if abs(df) > 0.10 else ""
        bg = "**" if abs(dg) > 0.10 else ""
        g_old = f"{o['gamma']:.3g}" if "gamma" in o else "—"
        g_d = f"{bg}{pct(o['gamma'], n['Gamma'])}{bg}" if "gamma" in o else ""
        out.append(f"| {b}{n['label']}{b} | {o['wave']:.3f} | {n['wave']:.4f} | "
                   f"{o.get('f_table', '—')} | {o.get('f_cog', '—')} | {n['f']:.4g} | {bf}{pct(fo, n['f'])}{bf} | "
                   f"{g_old} | {n['Gamma']:.3g} | {g_d} | {n['src']} |")
    out += ["", f"{n_big} of the kept transitions changed by more than 10% in f or Γ (or in λ by > 0.01 Å).", ""]

    out += ["## Transitions removed", "", "| Line | λ (Å) | Reason |", "|---|---|---|"]
    for o in removed:
        r = REMOVED.get((o["ion"], o["wave"]), "not found in the source tables near this wavelength")
        out.append(f"| {o['ion']} | {o['wave']} | {r} |")

    old_ions_set = {(o["ion"], t["wave"]) for o in old_ions for t in o["trs"]} | {(t["ion"], t["wave"]) for t in old_tr}
    added = [l for l in lines if not any(i == l["ion"] and abs(w - l["wave"]) < 0.1 for i, w in old_ions_set)]
    out += ["", f"## Transitions added ({len(added)})", "",
            ", ".join(l["label"] for l in added), ""]

    out += ["## Ionization energies (NIST ASD)", "",
            "| Ion | IE old (eV) | IE NIST (eV) | Δ (eV) | creation IE old | creation IE NIST | note |",
            "|---|---|---|---|---|---|---|"]
    for oi in old_ions:
        ni = ions.get(oi["ion"])
        if ni is None:
            out.append(f"| {oi['ion']} | {oi['ie']} | — | | {oi['form']} | — | ion not in new table |")
            continue
        d = (oi["ie"] - ni["ie"]) if (oi["ie"] is not None and ni.get("ie") is not None) else None
        dc = (oi["form"] - ni["ie_create"]) if oi["form"] is not None else None
        note = []
        if oi["ie"] is None and ni.get("ie") is not None:
            note.append("old table had no IE (wrongly marked fully ionized)")
        if d is not None and abs(d) > 0.01:
            note.append("IE wrong")
        if dc is not None and abs(dc) > 0.01:
            note.append("creation IE wrong")
        if not note:
            continue
        out.append(f"| {oi['ion']} | {oi['ie']} | {ni.get('ie', '—')} | {'' if d is None else f'{d:+.3f}'} | "
                   f"{oi['form']} | {ni['ie_create']} | {'; '.join(note)} |")
    out += ["", "Only ions whose old ionization or creation energy differed from NIST by more than 0.01 eV are listed.", ""]
    (ROOT / "DATA_CHANGES.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"kept {len(old_tab) - len(removed)}, removed {len(removed)}, added {len(added)}, big changes {n_big}")


if __name__ == "__main__":
    main()
